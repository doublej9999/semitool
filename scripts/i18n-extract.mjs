#!/usr/bin/env node
/**
 * Generates msgid-based tool copy resources and reports translation coverage.
 * English remains inline at call sites; translated locales live in one resource
 * per tool. Run with --check in CI to detect missing keys/translations.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { COPY_LOCALES, collectMsgids, sourceFiles } from './lib/i18n-scan.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcRoot = path.join(root, 'src');
const copyRoot = path.join(srcRoot, 'lib', 'i18n', 'tool-copy', 'resources');
const checkMode = process.argv.includes('--check');

function literal(node) {
  return node && (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) ? node.text : null;
}
function keyOf(node) {
  return node && (ts.isIdentifier(node) || ts.isStringLiteral(node)) ? node.text : null;
}
function readResource(resource) {
  const file = path.join(copyRoot, `${resource}.ts`);
  if (!existsSync(file)) return {};
  const source = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const out = {};
  const visit = (node) => {
    if (ts.isPropertyAssignment(node) && ts.isObjectLiteralExpression(node.initializer)) {
      const locale = keyOf(node.name);
      if (locale && COPY_LOCALES.includes(locale)) {
        out[locale] ??= {};
        for (const property of node.initializer.properties) {
          if (!ts.isPropertyAssignment(property)) continue;
          const key = keyOf(property.name);
          const value = literal(property.initializer);
          if (key !== null && value !== null) out[locale][key] = value;
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return out;
}
const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
function render(resource, msgids, previous) {
  const lines = [
    '/** Generated by `node scripts/i18n-extract.mjs`; translate values, not msgid keys. */',
    "import type { CopyResource } from '../types';",
    '',
    'export const COPY: CopyResource = {',
  ];
  for (const locale of COPY_LOCALES) {
    lines.push(`  ${quote(locale)}: {`);
    for (const msgid of [...msgids].sort((a, b) => a.localeCompare(b))) {
      lines.push(`    ${quote(msgid)}: ${quote(previous[locale]?.[msgid] ?? msgid)},`);
    }
    lines.push('  },');
  }
  lines.push('};', '', resource === 'shared' ? 'export const SHARED_COPY = COPY;' : 'export default COPY;', '');
  return lines.join('\n');
}

const grouped = new Map();
for (const file of sourceFiles(srcRoot)) {
  const { msgids, resource, dynamic } = collectMsgids(file, root);
  for (const warning of dynamic) console.warn(`[i18n-extract] dynamic msgid skipped: ${warning}`);
  if (!msgids.size) continue;
  if (!grouped.has(resource)) grouped.set(resource, new Set());
  for (const msgid of msgids) grouped.get(resource).add(msgid);
}

mkdirSync(copyRoot, { recursive: true });
let changed = 0;
let total = 0;
let missing = 0;
const active = new Set(grouped.keys());
for (const [resource, msgids] of [...grouped.entries()].sort()) {
  const previous = readResource(resource);
  const next = render(resource, msgids, previous);
  const file = path.join(copyRoot, `${resource}.ts`);
  const before = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (before !== next) {
    changed += 1;
    if (!checkMode) writeFileSync(file, next);
  }
  total += msgids.size;
  missing += [...msgids].filter((msgid) => COPY_LOCALES.some((locale) => !previous[locale]?.[msgid] || previous[locale][msgid] === msgid)).length;
  console.log(`${resource.padEnd(24)} ${String(msgids.size).padStart(4)} msgids ${String(missing).padStart(4)} untranslated cumulative`);
}

const toolIds = [...grouped.keys()].filter((resource) => resource !== 'shared').sort();
const registry = [
  '/** Generated by `node scripts/i18n-extract.mjs`; tool id -> copy chunk. */',
  "import type { CopyResource } from '../types';",
  '',
  'export const TOOL_COPY_LOADERS: Record<string, () => Promise<CopyResource>> = {',
  ...toolIds.map((toolId) => `  ${quote(toolId)}: () => import('./${toolId}').then((module) => module.COPY),`),
  '};',
  '',
].join('\n');
const registryFile = path.join(copyRoot, 'registry.ts');
const registryBefore = existsSync(registryFile) ? readFileSync(registryFile, 'utf8') : '';
if (registryBefore !== registry) {
  changed += 1;
  if (!checkMode) writeFileSync(registryFile, registry);
}

for (const entry of readdirSync(copyRoot, { withFileTypes: true })) {
  if (entry.isFile() && entry.name.endsWith('.ts') && !['index.ts', 'types.ts', 'msg.ts', 'shared.ts', 'registry.ts'].includes(entry.name) && !active.has(entry.name.slice(0, -3))) {
    if (!checkMode) writeFileSync(path.join(copyRoot, entry.name), '');
  }
}
console.log(`TOTAL ${total} msgids; ${missing} untranslated; ${changed} resource file(s) ${checkMode ? 'out of date' : 'written'}`);
if (checkMode && (changed > 0 || missing > 0)) process.exit(1);
